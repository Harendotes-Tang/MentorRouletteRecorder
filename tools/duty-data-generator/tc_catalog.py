#!/usr/bin/env python3
"""Offline TC catalogue parsing; generate.py owns every download and output write.

Only rows named in the TC client export enter the catalogue. The exported TC territory,
level and linked metadata are authoritative; no CN, GLOBAL or OpenCC fallback is accepted.
Category and expansion labels are the application's existing stable keys, projected from
TC links rather than borrowed from another region's duty rows.
"""

from __future__ import annotations

import csv
import io
import re

import game_names

REPOSITORY = game_names.TC_REPOSITORY
SHEETS = {
    "ContentFinderCondition": {
        "Name": "str", "TerritoryType": "TerritoryType", "ContentType": "ContentType",
        "ClassJobLevel{Required}": "byte", "ContentMemberType": "ContentMemberType",
    },
    "TerritoryType": {"ExVersion": "ExVersion"},
    "ContentType": {"Name": "str"},
    "ExVersion": {"Name": "str"},
    "ContentMemberType": {},
    "ContentRoulette": {"Name": "str", "IsInDutyFinder": "bit&02"},
}
# Existing application category keys, indexed by TC ContentType identity. Unnamed or
# unmapped TC types deliberately remain the existing Other bucket.
CATEGORY_KEYS = {
    1: "随机任务", 2: "四人迷宫", 3: "行会令", 4: "讨伐歼灭战", 5: "大型任务",
    6: "PVP", 7: "任务战斗", 9: "寻宝", 16: "采集活动", 19: "金碟游乐场",
    21: "深层迷宫", 26: "禁地探索", 27: "假面狂欢", 28: "绝境战",
    29: "南方战线", 30: "多变迷宫", 37: "团队任务", 38: "新月岛",
}
EXPANSION_KEYS = {
    0: "A Realm Reborn", 1: "Heavensward", 2: "Stormblood", 3: "Shadowbringers",
    4: "Endwalker", 5: "Dawntrail",
}
SOURCE_NOTE = (
    "Generated by tools/duty-data-generator/generate.py from the pinned "
    "thewakingsands/ffxiv-datamining-tc community export of the Traditional Chinese "
    "client. Source rows are client-export data, not live server acceptance. No CN, "
    "GLOBAL or OpenCC-only duty is added. Display data only: it never identifies a "
    "roulette and never makes a protocol profile usable. Game text is FINAL FANTASY XIV "
    "game text, © SQUARE ENIX CO., LTD., used for non-commercial display under the "
    "FINAL FANTASY XIV Materials Usage License with attribution. No licence file "
    "is supplied by the community export repository; credited here as the source."
)


def parse_csv(text, required, sheet):
    """Validate named columns, declared types, row widths and unique integer identities.

    Column order may change, but required names/types must still agree. A truncated or
    shifted row fails instead of silently associating a name with another territory.
    Returns all named columns, including optional party-size columns when supplied.
    """
    source = list(csv.reader(io.StringIO(text)))
    if len(source) < 4 or source[0][0:1] != ["key"] or source[1][0:1] != ["#"]:
        raise ValueError("%s.csv has no SaintCoinach header/data" % sheet)
    names, types = source[1], source[2]
    if len(source[0]) != len(names) or len(types) != len(names):
        raise ValueError("%s.csv header widths differ" % sheet)
    for name, expected_type in required.items():
        if names.count(name) != 1:
            raise ValueError("%s.csv needs exactly one %s column" % (sheet, name))
        if types[names.index(name)] != expected_type:
            raise ValueError("%s.csv %s type changed" % (sheet, name))
    columns = {name: index for index, name in enumerate(names) if name and name != "#"}
    if len(columns) != len([name for name in names if name and name != "#"]):
        raise ValueError("%s.csv repeats a named column" % sheet)
    result = {}
    for line, values in enumerate(source[3:], 4):
        if not values:
            continue
        if len(values) != len(names):
            raise ValueError("%s.csv row %d has a shifted/truncated width" % (sheet, line))
        row_id = integer(values[0], "%s.csv row %d key" % (sheet, line))
        if row_id in result:
            raise ValueError("%s.csv repeats row %d" % (sheet, row_id))
        result[row_id] = {name: values[index].strip() for name, index in columns.items()}
    if not result:
        raise ValueError("%s.csv has no source rows" % sheet)
    return result


def integer(value, label):
    """Require a decimal unsigned source value; do not coerce blanks or booleans."""
    if not isinstance(value, str) or not re.fullmatch(r"[0-9]+", value):
        raise ValueError("%s must be an unsigned integer" % label)
    return int(value)


def linked(rows, row_id, sheet):
    if row_id not in rows:
        raise ValueError("missing %s row %d referenced by named TC content" % (sheet, row_id))
    return rows[row_id]


def build_catalogues(texts, fetched, version, fetched_at):
    """Build both complete documents, or fail before either output can be written."""
    if not re.fullmatch(r"[0-9a-f]{40}", fetched.get("commit", "")):
        raise ValueError("TC provenance needs a full pinned commit")
    client_build = game_names.client_version(fetched.get("commit_message"))
    if not client_build:
        raise ValueError("TC commit message names no client build")
    if fetched.get("repository") != "https://github.com/" + REPOSITORY:
        raise ValueError("TC provenance names another repository")
    for sheet in SHEETS:
        # The fetch entry point owns the host/URL construction. This offline parser checks
        # the source identity and pin in the recorded path without acquiring network rules.
        suffix = "/%s/%s/%s.csv" % (REPOSITORY, fetched["commit"], sheet)
        matches = [request for request in fetched.get("requests", [])
                   if request.get("url", "").endswith(suffix)]
        if len(matches) != 1 or not re.fullmatch(r"[0-9a-f]{64}", matches[0].get("sha256", "")):
            raise ValueError("TC provenance has no pinned URL/hash for %s" % sheet)
    sheets = {}
    for sheet, required in SHEETS.items():
        if sheet not in texts:
            raise ValueError("missing TC source %s.csv" % sheet)
        sheets[sheet] = parse_csv(texts[sheet], required, sheet)
    duties = []
    absent_party_columns = 0
    for row_id, row in sorted(sheets["ContentFinderCondition"].items()):
        if not row["Name"]:
            continue
        if row_id == 0:
            raise ValueError("named TC content has a zero identity")
        territory_id = integer(row["TerritoryType"], "TC territory")
        category_id = integer(row["ContentType"], "TC content type")
        category = linked(sheets["ContentType"], category_id, "ContentType")
        if territory_id:
            territory = linked(sheets["TerritoryType"], territory_id, "TerritoryType")
            expansion_id = integer(territory["ExVersion"], "TC expansion")
            linked(sheets["ExVersion"], expansion_id, "ExVersion")
            expansion = EXPANSION_KEYS.get(expansion_id, "UNKNOWN")
        else:
            expansion = "UNKNOWN"
        member_id = integer(row["ContentMemberType"], "TC member type")
        member = linked(sheets["ContentMemberType"], member_id, "ContentMemberType")
        party_size = None
        if "MembersPerParty" in member and "PartyCount" in member:
            size = integer(member["MembersPerParty"], "TC members per party")
            parties = integer(member["PartyCount"], "TC party count")
            party_size = size * parties or None
        else:
            absent_party_columns += 1
        duties.append({
            "content_id": row_id, "territory_id": territory_id or None,
            "localized_name": row["Name"],
            "duty_category": CATEGORY_KEYS.get(category_id, "其他") if category["Name"] else "其他",
            "expansion": expansion,
            "level": integer(row["ClassJobLevel{Required}"], "TC required level"),
            "party_size": party_size, "enabled": True,
        })
    roulettes = []
    for row_id, row in sorted(sheets["ContentRoulette"].items()):
        if not row["Name"]:
            continue
        if row_id == 0 or row["IsInDutyFinder"] not in ("True", "False"):
            raise ValueError("invalid named TC roulette identity/visibility")
        roulettes.append({"roulette_id": row_id, "localized_name": row["Name"],
                          "enabled": row["IsInDutyFinder"] == "True"})
    if not duties or not roulettes:
        raise ValueError("TC source contains no named duties or roulettes")
    provenance = {
        "fetched_at_utc": fetched_at, "client_region": "TC", "client_build": client_build,
        "datamining_tc": fetched,
        "row_counts": {sheet: len(rows) for sheet, rows in sheets.items()},
        "named_duties": len(duties), "named_roulettes": len(roulettes),
        "party_size_missing_named_columns": absent_party_columns,
        "party_size_note": "Only named MembersPerParty/PartyCount columns are used. Unnamed "
                           "TC export columns are not guessed; unavailable party_size is null.",
        "source_content_types": {str(i): row["Name"]
                                 for i, row in sorted(sheets["ContentType"].items())},
        "source_expansions": {str(i): row["Name"]
                              for i, row in sorted(sheets["ExVersion"].items())},
        "category_keys": {str(i): key for i, key in CATEGORY_KEYS.items()},
        "expansion_keys": {str(i): key for i, key in EXPANSION_KEYS.items()},
        "note": "Only TC source rows/names/territories are used; no cross-region fallback. "
                "Client-export presence does not establish live availability or wire IDs. "
                + game_names.RAW_NOTE,
    }
    common = {"schema_version": 1, "region": "TC", "language": "zh-TW",
              "data_version": version, "updated_at_utc": fetched_at,
              "source": SOURCE_NOTE, "provenance": provenance}
    return ({**common, "sample": False, "duties": duties},
            {**common, "roulettes": roulettes})
