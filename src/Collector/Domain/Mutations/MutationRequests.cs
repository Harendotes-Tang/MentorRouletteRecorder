using MentorRecorder.Collector.Domain.Time;

namespace MentorRecorder.Collector.Domain.Mutations;

/// <summary>
/// The correctable fields of a run, as a patch.
///
/// A correction has to distinguish "leave this field alone" from "set this field to null",
/// so the patch carries the values plus the set of field names the caller named.
/// <see cref="Specified"/> is the authority; a value whose name is absent is ignored no
/// matter what it holds (docs/manual-correction.md section 7).
/// </summary>
public sealed record RunChangeSet
{
    /// <summary>Field names the caller explicitly supplied, in wire spelling.</summary>
    public IReadOnlySet<string> Specified { get; init; } = new HashSet<string>(StringComparer.Ordinal);

    /// <summary>Duty content id.</summary>
    public int? ContentId { get; init; }

    /// <summary>Localized duty name.</summary>
    public string? DutyName { get; init; }

    /// <summary>Duty category.</summary>
    public string? DutyCategory { get; init; }

    /// <summary>Job id; the job name and role are recomputed from it.</summary>
    public int? JobId { get; init; }

    /// <summary>Match time.</summary>
    public DateTimeOffset? MatchedAtUtc { get; init; }

    /// <summary>Duty entry time.</summary>
    public DateTimeOffset? EnteredAtUtc { get; init; }

    /// <summary>Run end time.</summary>
    public DateTimeOffset? EndedAtUtc { get; init; }

    /// <summary>Explicit duration; when omitted it is recomputed from the corrected times.</summary>
    public long? DurationMs { get; init; }

    /// <summary>Final result bucket.</summary>
    public RunResult? Result { get; init; }

    /// <summary>Whether the run counts towards the achievement goal.</summary>
    public bool? ContributesToGoal { get; init; }

    /// <summary>Free-text note.</summary>
    public string? Note { get; init; }

    /// <summary>
    /// Acknowledgement of a run the machine could not finish on its own. Only <c>false</c>
    /// is accepted: a person may confirm a 待复核 record, never push one back into review
    /// (docs/manual-correction.md section 7).
    /// </summary>
    public bool? PendingReview { get; init; }

    /// <summary>True when the caller named <paramref name="field"/>.</summary>
    /// <param name="field">Wire field name, for example <c>entered_at_utc</c>.</param>
    public bool Has(string field) => Specified.Contains(field);

    /// <summary>True when the caller named no field at all.</summary>
    public bool IsEmpty => Specified.Count == 0;
}

/// <summary>Field names accepted by <see cref="RunChangeSet"/>, in wire spelling.</summary>
public static class RunFields
{
    /// <summary>content_id.</summary>
    public const string ContentId = "content_id";

    /// <summary>duty_name.</summary>
    public const string DutyName = "duty_name";

    /// <summary>duty_category.</summary>
    public const string DutyCategory = "duty_category";

    /// <summary>job_id.</summary>
    public const string JobId = "job_id";

    /// <summary>job_name, derived from job_id.</summary>
    public const string JobName = "job_name";

    /// <summary>role, derived from job_id.</summary>
    public const string Role = "role";

    /// <summary>matched_at_utc.</summary>
    public const string MatchedAtUtc = "matched_at_utc";

    /// <summary>entered_at_utc.</summary>
    public const string EnteredAtUtc = "entered_at_utc";

    /// <summary>ended_at_utc.</summary>
    public const string EndedAtUtc = "ended_at_utc";

    /// <summary>duration_ms.</summary>
    public const string DurationMs = "duration_ms";

    /// <summary>result.</summary>
    public const string Result = "result";

    /// <summary>contributes_to_goal.</summary>
    public const string ContributesToGoal = "contributes_to_goal";

    /// <summary>note.</summary>
    public const string Note = "note";

    /// <summary>soft_deleted.</summary>
    public const string SoftDeleted = "soft_deleted";

    /// <summary>pending_review.</summary>
    public const string PendingReview = "pending_review";

    /// <summary>manually_corrected.</summary>
    public const string ManuallyCorrected = "manually_corrected";

    /// <summary>Every field a client may name inside a correction.</summary>
    public static IReadOnlySet<string> Correctable { get; } = new HashSet<string>(StringComparer.Ordinal)
    {
        ContentId, DutyName, DutyCategory, JobId, MatchedAtUtc, EnteredAtUtc, EndedAtUtc,
        DurationMs, Result, ContributesToGoal, Note, PendingReview,
    };
}

/// <summary>Request to create a run by hand (docs/manual-correction.md section 1).</summary>
public sealed record CreateManualRunCommand
{
    /// <summary>Idempotency key generated by the client.</summary>
    public required string RequestId { get; init; }

    /// <summary>Mandatory explanation, 1 to 500 characters.</summary>
    public required string Reason { get; init; }

    /// <summary>Final result bucket.</summary>
    public required RunResult Result { get; init; }

    /// <summary>Duty content id.</summary>
    public int? ContentId { get; init; }

    /// <summary>Localized duty name; falls back to the duty catalog.</summary>
    public string? DutyName { get; init; }

    /// <summary>Duty category; falls back to the duty catalog.</summary>
    public string? DutyCategory { get; init; }

    /// <summary>Job id; the job name and role are derived from it.</summary>
    public int? JobId { get; init; }

    /// <summary>Match time.</summary>
    public DateTimeOffset? MatchedAtUtc { get; init; }

    /// <summary>Duty entry time; required unless the result is CANCELLED_BEFORE_ENTRY.</summary>
    public DateTimeOffset? EnteredAtUtc { get; init; }

    /// <summary>Run end time; required when the result is COMPLETED.</summary>
    public DateTimeOffset? EndedAtUtc { get; init; }

    /// <summary>Explicit duration; when omitted it is derived from the two times.</summary>
    public long? DurationMs { get; init; }

    /// <summary>True when duration_ms was supplied, including an explicit null (unknown).</summary>
    public bool DurationSpecified { get; init; }

    /// <summary>Whether the run counts towards the achievement goal.</summary>
    public bool ContributesToGoal { get; init; } = true;

    /// <summary>Free-text note.</summary>
    public string? Note { get; init; }
}

/// <summary>Request to correct an existing run.</summary>
/// <param name="RequestId">Idempotency key generated by the client.</param>
/// <param name="RunId">Run to correct.</param>
/// <param name="ExpectedRevision">Revision the client believes is current.</param>
/// <param name="Reason">Mandatory explanation, 1 to 500 characters.</param>
/// <param name="Changes">Fields to change.</param>
public sealed record CorrectRunCommand(
    string RequestId,
    string RunId,
    int ExpectedRevision,
    string Reason,
    RunChangeSet Changes);

/// <summary>Request to soft delete, restore, or undo the newest revision of a run.</summary>
/// <param name="RequestId">Idempotency key generated by the client.</param>
/// <param name="RunId">Run to act on.</param>
/// <param name="ExpectedRevision">Revision the client believes is current.</param>
/// <param name="Reason">Mandatory explanation, 1 to 500 characters.</param>
public sealed record RunReasonCommand(
    string RequestId,
    string RunId,
    int ExpectedRevision,
    string Reason);

/// <summary>Request to change the achievement baseline.</summary>
/// <param name="RequestId">Idempotency key generated by the client.</param>
/// <param name="GoalCount">Target completions; at least 1.</param>
/// <param name="BaselineCompletedCount">Self-reported prior completions; at least 0.</param>
/// <param name="BaselineEffectiveAt">When the baseline takes effect.</param>
/// <param name="Reason">Mandatory explanation, 1 to 500 characters.</param>
public sealed record UpdateAchievementBaselineCommand(
    string RequestId,
    int GoalCount,
    int BaselineCompletedCount,
    DateTimeOffset BaselineEffectiveAt,
    string Reason);

/// <summary>Common tail of every mutating response, mirroring <c>$defs/MutationResult</c>.</summary>
/// <param name="RunId">Run the mutation applied to.</param>
/// <param name="Revision">Revision after the mutation.</param>
/// <param name="AuditEventId">Identifier of the appended audit row.</param>
/// <param name="IdempotentReplay">True when this replays an earlier request with the same id.</param>
/// <param name="Run">Run as it stands after the mutation.</param>
public sealed record RunMutationOutcome(
    string RunId,
    int Revision,
    string AuditEventId,
    bool IdempotentReplay,
    MentorRun? Run);

/// <summary>
/// Request to write, replace or clear the 导随心得 of one run.
///
/// It carries neither a reason nor an expected revision: a reflection is the user's own diary
/// entry rather than a correction of a captured fact, so there is nothing to justify and no
/// observed value to race against.
/// </summary>
/// <param name="RequestId">Idempotency key generated by the client.</param>
/// <param name="RunId">Run to attach the reflection to; soft-deleted runs are allowed.</param>
/// <param name="Mood">Mood the user picked.</param>
/// <param name="Text">Trimmed text, or null when the request clears the reflection.</param>
public sealed record SetRunReflectionCommand(
    string RequestId,
    string RunId,
    ReflectionMood Mood,
    string? Text);

/// <summary>Outcome of a reflection write.</summary>
/// <param name="RunId">Run the reflection belongs to.</param>
/// <param name="Reflection">Reflection as stored, or null when it was cleared.</param>
/// <param name="Run">Run as it stands after the write, with its reflection attached.</param>
/// <param name="IdempotentReplay">True when this replays an earlier request with the same id.</param>
public sealed record ReflectionMutationOutcome(
    string RunId,
    RunReflection? Reflection,
    MentorRun? Run,
    bool IdempotentReplay);

/// <summary>Outcome of a baseline change.</summary>
/// <param name="Settings">Settings as stored after the change.</param>
/// <param name="AuditEventId">Identifier of the audit record.</param>
/// <param name="IdempotentReplay">True when this replays an earlier request with the same id.</param>
public sealed record BaselineMutationOutcome(
    AchievementSettings Settings,
    string AuditEventId,
    bool IdempotentReplay);

/// <summary>Helpers shared by the mutation validators.</summary>
public static class MutationText
{
    /// <summary>Longest accepted reason, per the contract.</summary>
    public const int MaxReasonLength = 500;

    /// <summary>True when <paramref name="reason"/> is a usable explanation.</summary>
    /// <param name="reason">Candidate reason.</param>
    public static bool IsUsableReason(string? reason) =>
        !string.IsNullOrWhiteSpace(reason) && reason.Trim().Length <= MaxReasonLength;

    /// <summary>Normalises a timestamp to the millisecond precision the schema mandates.</summary>
    /// <param name="value">Timestamp, or null.</param>
    public static DateTimeOffset? Normalize(DateTimeOffset? value) =>
        value is null ? null : UtcTimestamp.Truncate(value.Value);
}
